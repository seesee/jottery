package com.jottery.android.database

import androidx.room.testing.MigrationTestHelper
import androidx.sqlite.db.SupportSQLiteDatabase
import androidx.test.platform.app.InstrumentationRegistry
import com.jottery.android.util.DateUtils
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import java.time.Duration
import java.time.Instant

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [35])
class MigrationTest {
    private val dbName = "migration-test"

    @get:Rule
    val helper = MigrationTestHelper(
        InstrumentationRegistry.getInstrumentation(),
        JotteryDatabase::class.java,
    )

    private val allMigrations = arrayOf(
        JotteryDatabase.MIGRATION_1_2,
        JotteryDatabase.MIGRATION_2_3,
        JotteryDatabase.MIGRATION_3_4,
        JotteryDatabase.MIGRATION_4_5,
    )

    /** Columns every version has, so a test can seed the oldest database there is. */
    private fun SupportSQLiteDatabase.seedNote() = execSQL(
        "INSERT INTO notes (id, created_at, modified_at, content, tags, attachments, pinned, archived, " +
            "locked, deleted, version, word_wrap, syntax_language, show_preview, needs_sync) " +
            "VALUES ('n', 't', 't', 'ciphertext', 'g', '[]', 1, 0, 0, 0, 7, 1, 'markdown', 0, 1)"
    )

    // Schemas 1 and 2 were never committed. They were generated by running Room over the
    // entities at bae86f4c and 139d379c, and doing the same at 23aed3ca gave the committed
    // 3.json exactly. The entities made salt and iterations nullable in version 2, but
    // MIGRATION_1_2 didn't, so a version 1 vault is only right after both steps.

    @Test fun `a version 1 vault reaches today with its key intact`() {
        helper.createDatabase(dbName, 1).use { db ->
            db.execSQL(
                "INSERT INTO encryption_metadata (id, salt, iterations, created_at, algorithm, verification) " +
                    "VALUES (1, 'the-salt', 600000, 't', 'AES-256-GCM', 'the-token')"
            )
            db.seedNote()
            db.execSQL(
                "INSERT INTO attachments (id, filename, mime_type, size, data) " +
                    "VALUES ('a', 'divorce-petition.pdf', 'application/pdf', 3, x'010203')"
            )
            db.execSQL("INSERT INTO sync_metadata (id, sync_enabled) VALUES (1, 0)")
        }

        helper.runMigrationsAndValidate(dbName, 5, true, *allMigrations).use { db ->
            db.query(
                "SELECT salt, iterations, verification, algorithm, envelope_version, device_salt, " +
                    "local_wrapped_master FROM encryption_metadata WHERE id = 1"
            ).use {
                assertTrue("the vault can't unlock without this row", it.moveToFirst())
                assertEquals("the-salt", it.getString(0))
                assertEquals(600_000, it.getInt(1))
                assertEquals("the-token", it.getString(2))
                assertEquals("AES-256-GCM", it.getString(3))
                assertTrue(it.isNull(4))
                assertTrue(it.isNull(5))
                assertTrue(it.isNull(6))
            }
            db.query("SELECT content, pinned, version, needs_sync FROM notes WHERE id = 'n'").use {
                assertTrue(it.moveToFirst())
                assertEquals("ciphertext", it.getString(0))
                assertEquals(1, it.getInt(1))
                assertEquals(7, it.getInt(2))
                assertEquals("still to be sent", 1, it.getInt(3))
            }
            db.query("SELECT size, data FROM attachments WHERE id = 'a'").use {
                assertTrue(it.moveToFirst())
                assertEquals(3, it.getBlob(1).size)
            }
        }
    }

    @Test fun `a version 2 vault on an envelope, with no salt, reaches today`() {
        helper.createDatabase(dbName, 2).use { db ->
            db.execSQL(
                "INSERT INTO encryption_metadata (id, created_at, algorithm, verification, envelope_version, " +
                    "device_salt, local_wrapped_master, wrapping_kdf_version) " +
                    "VALUES (1, 't', 'AES-256-GCM', 'the-token', 1, 'device-salt', 'wrapped', 1)"
            )
            db.execSQL("INSERT INTO sync_metadata (id, sync_enabled, user_id) VALUES (1, 1, 'user')")
            db.seedNote()
        }

        helper.runMigrationsAndValidate(dbName, 5, true, *allMigrations.drop(1).toTypedArray()).use { db ->
            db.query(
                "SELECT salt, iterations, envelope_version, device_salt, local_wrapped_master, wrapping_kdf_version " +
                    "FROM encryption_metadata WHERE id = 1"
            ).use {
                assertTrue(it.moveToFirst())
                assertTrue(it.isNull(0))
                assertTrue(it.isNull(1))
                assertEquals(1, it.getInt(2))
                assertEquals("device-salt", it.getString(3))
                assertEquals("wrapped", it.getString(4))
                assertEquals(1, it.getInt(5))
            }
            db.query("SELECT user_id FROM sync_metadata WHERE id = 1").use {
                assertTrue(it.moveToFirst())
                assertEquals("user", it.getString(0))
            }
        }
    }

    @Test fun `1 to 3 ends on exactly the schema version 3 declared`() {
        helper.createDatabase(dbName, 1).close()

        helper.runMigrationsAndValidate(dbName, 3, true, JotteryDatabase.MIGRATION_1_2, JotteryDatabase.MIGRATION_2_3).close()
    }

    @Test fun `2 to 3 ends on exactly the schema version 3 declared`() {
        helper.createDatabase(dbName, 2).close()

        helper.runMigrationsAndValidate(dbName, 3, true, JotteryDatabase.MIGRATION_2_3).close()
    }

    @Test fun `3 to 4 never rewrites an attachment`() {
        helper.createDatabase(dbName, 3).use { db ->
            db.execSQL(
                "INSERT INTO attachments (id, filename, mime_type, size, data) " +
                    "VALUES ('a', 'divorce-petition.pdf', 'application/pdf', 3, x'010203')"
            )
            db.execSQL("CREATE TABLE attachment_writes (id TEXT)")
            db.execSQL(
                "CREATE TRIGGER count_attachment_writes AFTER UPDATE ON attachments " +
                    "BEGIN INSERT INTO attachment_writes VALUES (new.id); END"
            )
        }

        helper.runMigrationsAndValidate(dbName, 4, false, JotteryDatabase.MIGRATION_3_4).use { db ->
            db.query("SELECT COUNT(*) FROM attachment_writes").use {
                it.moveToFirst()
                assertEquals(0, it.getInt(0))
            }
        }
    }

    @Test fun `3 to 4 keeps every row and adds the flag`() {
        helper.createDatabase(dbName, 3).use { db ->
            db.execSQL(
                "INSERT INTO attachments (id, filename, mime_type, size, data) " +
                    "VALUES ('a', 'divorce-petition.pdf', 'application/pdf', 3, x'010203')"
            )
            db.execSQL(
                "INSERT INTO notes (id, created_at, modified_at, content, tags, attachments, pinned, archived, " +
                    "locked, deleted, version, word_wrap, syntax_language, show_preview, needs_sync) " +
                    "VALUES ('n', 't', 't', 'c', 'g', '[]', 0, 0, 0, 0, 1, 1, 'markdown', 0, 0)"
            )
        }

        helper.runMigrationsAndValidate(dbName, 4, true, JotteryDatabase.MIGRATION_3_4).use { db ->
            db.query("SELECT filename, mime_type, size, data, uploaded FROM attachments WHERE id = 'a'").use {
                it.moveToFirst()
                assertEquals("divorce-petition.pdf", it.getString(0))
                assertEquals("application/pdf", it.getString(1))
                assertEquals(3, it.getInt(2))
                assertEquals(3, it.getBlob(3).size)
                assertEquals(0, it.getInt(4))
            }
            db.query("SELECT COUNT(*) FROM notes").use {
                it.moveToFirst()
                assertEquals(1, it.getInt(0))
            }
        }
    }

    @Test fun `4 to 5 keeps the connection and starts with nothing known about the wrapped key`() {
        helper.createDatabase(dbName, 4).use { db ->
            db.execSQL(
                "INSERT INTO sync_metadata (id, last_sync_at, sync_enabled, user_id) " +
                    "VALUES (1, '2026-01-01T00:00:00.000Z', 1, 'user')"
            )
            for ((id, deleted, deletedAt) in listOf(Triple("live", 0, "NULL"), Triple("bin", 1, "'2020-01-01T00:00:00.000Z'"))) {
                db.execSQL(
                    "INSERT INTO notes (id, created_at, modified_at, content, tags, attachments, pinned, archived, " +
                        "locked, deleted, deleted_at, version, word_wrap, syntax_language, show_preview, needs_sync) " +
                        "VALUES ('$id', 't', 't', 'c', 'g', '[]', 0, 0, 0, $deleted, $deletedAt, 1, 1, 'markdown', 0, 0)"
                )
            }
        }

        helper.runMigrationsAndValidate(dbName, 5, true, JotteryDatabase.MIGRATION_4_5).use { db ->
            db.query(
                "SELECT last_sync_at, user_id, wrapped_key_opened, pending_wrapped_key, pull_cursor, cursor_adopted " +
                    "FROM sync_metadata WHERE id = 1"
            ).use {
                it.moveToFirst()
                assertEquals("2026-01-01T00:00:00.000Z", it.getString(0))
                assertEquals("user", it.getString(1))
                assertEquals(0, it.getInt(2))
                assertEquals(true, it.isNull(3))
                assertEquals(true, it.isNull(4))
                assertEquals(0, it.getInt(5))
            }
            db.query("SELECT local_deleted_at FROM notes WHERE id = 'live'").use {
                it.moveToFirst()
                assertEquals(true, it.isNull(0))
            }
            // A date from the server mustn't purge it, so its time starts now
            db.query("SELECT deleted_at, local_deleted_at FROM notes WHERE id = 'bin'").use {
                it.moveToFirst()
                assertEquals("2020-01-01T00:00:00.000Z", it.getString(0))
                val binned = DateUtils.parseISO8601(it.getString(1))!!
                assertTrue(Duration.between(binned, Instant.now()).abs() < Duration.ofMinutes(5))
            }
        }
    }
}
